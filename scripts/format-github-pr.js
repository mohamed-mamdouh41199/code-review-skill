#!/usr/bin/env node

/**
 * GitHub PR Code Review Formatter
 * Formats code review as a GitHub PR comment
 * Usage: node format-github-pr.js
 */

class GitHubPRCommentFormatter {
  constructor() {
    this.issues = {
      best_practices: [],
      security: [],
      performance: []
    };
  }

  addIssue(category, severity, title, description, suggestion, line = null) {
    this.issues[category].push({
      severity,
      title,
      description,
      suggestion,
      line
    });
  }

  getSeverityLabel(severity) {
    const labels = {
      critical: '🔴 Critical',
      high: '🟠 High',
      medium: '🟡 Medium',
      low: '🟢 Low'
    };
    return labels[severity] || severity;
  }

  countBySeverity(issues) {
    const counts = { critical: 0, high: 0, medium: 0, low: 0 };
    issues.forEach(issue => counts[issue.severity]++);
    return counts;
  }

  formatCollapsible(title, issues) {
    if (issues.length === 0) return '';

    const counts = this.countBySeverity(issues);
    const severity = counts.critical > 0 ? 'critical' : 
                     counts.high > 0 ? 'high' : 
                     counts.medium > 0 ? 'medium' : 'low';
    
    const emoji = {
      critical: '🔴',
      high: '🟠', 
      medium: '🟡',
      low: '🟢'
    }[severity];

    let html = `<details>\n<summary>${emoji} <strong>${title}</strong> (${issues.length})</summary>\n\n`;

    // Group by severity
    const bySeverity = {};
    issues.forEach(issue => {
      if (!bySeverity[issue.severity]) {
        bySeverity[issue.severity] = [];
      }
      bySeverity[issue.severity].push(issue);
    });

    const severityOrder = ['critical', 'high', 'medium', 'low'];
    
    for (const sev of severityOrder) {
      if (bySeverity[sev]) {
        html += `\n### ${this.getSeverityLabel(sev)}\n\n`;
        
        bySeverity[sev].forEach((issue, idx) => {
          html += `${idx + 1}. **${issue.title}**\n`;
          html += `   - ${issue.description}\n`;
          html += `   - **Suggestion**: ${issue.suggestion}\n\n`;
        });
      }
    }

    html += '</details>\n\n';
    return html;
  }

  toGitHubComment() {
    const allIssues = [
      ...this.issues.security,
      ...this.issues.best_practices,
      ...this.issues.performance
    ];

    if (allIssues.length === 0) {
      return '## ✅ Code Review Passed\n\nNo issues found!';
    }

    const securityCounts = this.countBySeverity(this.issues.security);
    const bpCounts = this.countBySeverity(this.issues.best_practices);
    const perfCounts = this.countBySeverity(this.issues.performance);

    const hasCritical = securityCounts.critical > 0 || 
                        bpCounts.critical > 0 || 
                        perfCounts.critical > 0;

    let comment = '## 🔍 Code Review\n\n';

    // Status badge
    if (hasCritical) {
      comment += '**Status**: ❌ Changes Required (Critical Issues Found)\n\n';
    } else {
      comment += '**Status**: ⚠️ Review Required\n\n';
    }

    // Summary counts
    comment += '### Summary\n\n';
    comment += `| Category | Critical | High | Medium | Low |\n`;
    comment += `|----------|----------|------|--------|-----|\n`;
    comment += `| Security | ${securityCounts.critical} | ${securityCounts.high} | ${securityCounts.medium} | ${securityCounts.low} |\n`;
    comment += `| Best Practices | ${bpCounts.critical} | ${bpCounts.high} | ${bpCounts.medium} | ${bpCounts.low} |\n`;
    comment += `| Performance | ${perfCounts.critical} | ${perfCounts.high} | ${perfCounts.medium} | ${perfCounts.low} |\n\n`;

    // Detailed sections
    comment += this.formatCollapsible(
      'Security Vulnerabilities',
      this.issues.security
    );

    comment += this.formatCollapsible(
      'Best Practices & Code Quality',
      this.issues.best_practices
    );

    comment += this.formatCollapsible(
      'Performance Optimizations',
      this.issues.performance
    );

    // Action items
    comment += '### Next Steps\n\n';
    if (hasCritical) {
      comment += '1. ⛔ **Critical issues must be addressed** before merging\n';
    }
    if (securityCounts.high > 0 || bpCounts.high > 0 || perfCounts.high > 0) {
      comment += '2. 🔧 **High-priority issues** should be fixed\n';
    }
    comment += '3. 💡 **Medium and low** suggestions can be addressed in follow-ups\n';
    comment += '\n---\n\n';
    comment += '_Generated by [code-review skill](https://github.com/yourusername/code-review-skill)_\n';

    return comment;
  }

  // Example usage
  static example() {
    const formatter = new GitHubPRCommentFormatter();

    // Security
    formatter.addIssue(
      'security',
      'critical',
      'SQL Injection in user lookup',
      'Line 42: User input directly concatenated into SQL query',
      'Use parameterized queries: `db.query("SELECT * FROM users WHERE id = ?", [id])`'
    );

    formatter.addIssue(
      'security',
      'high',
      'Missing CSRF token validation',
      'Form submissions bypass CSRF protection',
      'Add csrf middleware to protect POST/PUT/DELETE endpoints'
    );

    // Best practices
    formatter.addIssue(
      'best_practices',
      'high',
      'Unhandled promise rejection',
      'Line 15: fetchData() promise has no error handler',
      'Add .catch() handler or use try-catch with async/await'
    );

    formatter.addIssue(
      'best_practices',
      'medium',
      'Hardcoded configuration',
      'API key is hardcoded in source code',
      'Move to environment variables: `process.env.API_KEY`'
    );

    // Performance
    formatter.addIssue(
      'performance',
      'high',
      'N+1 Database Query Problem',
      'Loop makes individual queries instead of batching',
      'Use Promise.all() or aggregation: `db.collection().find().toArray()`'
    );

    return formatter;
  }
}

// Example output
if (require.main === module) {
  const example = GitHubPRCommentFormatter.example();
  console.log(example.toGitHubComment());
}

module.exports = GitHubPRCommentFormatter;
